## 📖 Reading B: A City Up Against the Wall

People walk through a flooded Piazza San Marco in Venice, Italy.

The disastrous flood of November 12, 2019, started out as a gentle flow into Piazza San Marco at around 6 a.m. Two hours later, the rising waters stopped rising at about a meter above normal sea level. Ninety percent of the city was still dry. The residents of Venice, Italy, began to relax. It seemed to be just another slightly unpleasant acqua alta, or high tide, in the lagoon, but that was just the beginning.

The calm conditions lasted until 4 p.m., just before night fell. Then, alarms began to go off. Within an hour, the ancient squares and narrow walkways along the city's 40 kilometers of canals had vanished under fierce waves of seawater. "This wasn't simply a tide," says Marco Malafonte, who co-owns a property management firm with his wife, Caroline Gucchierato. "It was a colossal wave, something we'd never seen before. A tsunami."

The couple went off in different directions, joining volunteer rescue teams. In the San Marco quarter, Venice's lowest-lying district, Gucchierato helped an elderly French tourist. She was standing up to her neck against a stone wall in the fast-moving flood. She had put her baby grandson on the wall, holding onto him until help arrived. Vaporettos, the famous Venetian water buses, "were thrown up onto walkways and bridges like children's toys," recalls Malafonte.

At 8 p.m., the water finally reached its peak at just under two meters, with 85 percent of the city underwater. It was the second highest flood tide ever recorded in Venice, just over 20 centimeters above the average height of its residents.

*A lagoon is a body of water separated by a section of land from a larger body, such as the ocean.*

### Il Mose per Venezia

Three of the Moses barriers are raised as a boat passes by.

The occasional destructive acqua alta used to happen a few times each century. But as sea levels rise around the world, it has become the new normal. Over the last century, 25 acque alte in Venice have been 1.5 meters or higher. Of these, more than half have happened since December 2009.

This has convinced Venetian officials to spend billions of euros on a series of moveable walls to block high waters from entering the city. Formally named the Experimental Electromechanical Model, or Moses for short, the system seems to be working. In effect, Moses separates Venice from the sea temporarily. It closes off the entire Venetian Lagoon from dangerous tides in the stormy Adriatic. The ambitious engineering experiment is a desperate attempt to prevent disaster for one of the world's most beautiful cities.

Work on Moses began back in 1987, and some of Europe's largest construction firms have helped with the project under the direction of the Italian government. The Italian Ministry of Infrastructure and Transport and its partners began making the system's parts in 2003, and on-site work began in 2008. By late 2020, the partially completed barriers were ready for live testing. The long-term goal is to protect Venice until at least the end of the century, when sea levels may have risen another 1.5 meters.

Of course, Moses is much more than a simple wall. It is more like a mechanical dam, made up of 78 hollow barriers that are filled with water and hidden on the sea floor when they are not needed. When a dangerously high tide is expected, water is pumped out of the barriers, which then float to the top. A control center sits on an island that separates the two largest barriers. A team of 100 workers is needed to monitor the control system, to perform various tasks in underwater tunnels, and to bring workers to and from the control center.

Each barrier is 20 meters wide, but their height varies between 20 and 30 meters, depending on how deep the water is. One unique characteristic of the wall is that the barriers can be operated independently. This is useful for several reasons: First, the operators might only want to slow the tide, not stop it entirely. Second, keeping a few barriers lowered allows ships to pass. Last, if one barrier malfunctions, Moses as a whole would still work. In all, it takes 32 minutes to raise the barriers, and they can stop tides three meters above what is considered normal.

Moses first went into action on October 3, 2020, to block a tide more than a meter high. And finally, after its long struggle with high waters, Venice remained amazingly dry, proving the project worked. Over the following 20 months, the gates lifted 33 more times, in tests from 30 to 92 minutes long, with the same results.

### The Price of Safety

Although Moses has been an effective solution so far, it's not cheap. Its cost to date has increased to around €8 billion—far more than expected. In addition, it's expensive to use and requires a lot of labor to maintain and operate. It also doesn't keep some of the lower-lying areas of the city from flooding, like Piazza San Marco. As Venice experiences more frequent and higher floods, Moses will be tested to its limits, being used far more often than originally planned. But at least for now, the barriers are helping to protect a special city.

Salt marshes in the Venetian lagoon. Unfortunately, Moses may be a danger to the salt marshes in the lagoon it is supposed to protect. When the tide comes in, it covers the grasses with water. It also leaves sediment, which helps the plants to grow. The plants form the structure of the lagoon. Their roots hold the sand in place. When the tide is blocked by the barriers, it cannot "feed" the lagoon. To reduce potential damage, the barriers are raised for only three to four hours at a time.

*Sediment settles to the bottom in a liquid. Sediment in a lagoon may include sand, dirt, and the remains of dead plants and animals.*

