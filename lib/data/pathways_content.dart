### CITIES AS SOLUTIONS?

In the 19th and early 20th centuries, large urban areas began to grow and spread. Many people viewed cities largely in negative terms—crowded, dirty, unhealthy places full of disease and crime. People feared that as cities got bigger, living conditions would get worse. Recent decades, however, have seen a widespread change in attitudes toward urbanization. Many experts believe that urbanization is good news. Although negative aspects such as pollution and urban slums remain serious problems, many urban planners now believe big cities might help solve the problem of Earth's growing population.

